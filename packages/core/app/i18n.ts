export type Dict = typeof en;

/** The chrome speaks open-doc's five languages. `zh` is Traditional Chinese (Taiwan). */
export type Lang = 'en' | 'zh' | 'zh-CN' | 'ja' | 'ko';
export const LANGS: { id: Lang; label: string; html: string }[] = [
  { id: 'en', label: 'English', html: 'en' },
  { id: 'zh', label: '繁體中文', html: 'zh-Hant' },
  { id: 'zh-CN', label: '简体中文', html: 'zh-Hans' },
  { id: 'ja', label: '日本語', html: 'ja' },
  { id: 'ko', label: '한국어', html: 'ko' },
];
const DICTS: Record<Lang, Dict> = { en, zh, 'zh-CN': zhCN, ja, ko };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('open-spreadsheet:lang') as Lang | null;
    if (saved && saved in DICTS) return saved;
  } catch {
    // Storage blocked: fall back to the browser language.
  }
  const nav = navigator.language.toLowerCase();
  if (nav.startsWith('zh')) return /cn|sg|hans/.test(nav) ? 'zh-CN' : 'zh';
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('ko')) return 'ko';
  return 'en';
}

export let lang: Lang = initialLang();
export let T: Dict = DICTS[lang];
/** Chinese content (templates, long dates) for both scripts. */
export const isZh = () => lang === 'zh' || lang === 'zh-CN';
/** The locale for dates and sorting. */
export const locale = () => ({ en: 'en', zh: 'zh-TW', 'zh-CN': 'zh-CN', ja: 'ja-JP', ko: 'ko-KR' })[lang];

export function setLang(next: Lang): void {
  lang = next;
  T = DICTS[next];
  document.documentElement.lang = LANGS.find((l) => l.id === next)!.html;
  try {
    localStorage.setItem('open-spreadsheet:lang', next);
  } catch {
    // Not remembered; still applies now.
  }
}
